-- Como usar: Supabase > SQL Editor > New query > cole tudo > Run.
-- Antes de rodar, troque 'seu@email.com' (no fim do arquivo) pelo e-mail da equipe.

-- Equipe autorizada ---------------------------------------------------------
create table if not exists public.staff (email text primary key);
alter table public.staff enable row level security;   -- sem policies: ninguém lê pela API

create or replace function public.is_staff() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.staff where email = lower(coalesce(auth.jwt() ->> 'email', '')));
$$;
grant execute on function public.is_staff() to anon, authenticated;

-- Tabelas -------------------------------------------------------------------
create table if not exists public.categories (
  name text primary key,
  position int not null default 0
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  sku text not null default '',
  name text not null,
  category text not null,
  price numeric(10,2) not null check (price >= 0),
  old_price numeric(10,2),
  tag text not null default '',
  description text not null default '',
  colors jsonb not null default '[]',    -- [["Rosé","#e8a58f"], ...]
  stock jsonb not null default '{}',     -- {"P":3,"M":5}
  images jsonb not null default '[]',    -- ["https://...jpg", ...]
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  code text not null,
  customer jsonb not null,
  items jsonb not null check (jsonb_typeof(items) = 'array' and jsonb_array_length(items) between 1 and 50),
  subtotal numeric(10,2) not null default 0,
  discount numeric(10,2) not null default 0,
  shipping numeric(10,2) not null default 0,
  total numeric(10,2) not null,
  payment text not null default '',
  status text not null default 'novo' check (status in ('novo','confirmado','cancelado')),
  created_at timestamptz not null default now()
);

-- Segurança (RLS) -----------------------------------------------------------
alter table public.categories enable row level security;
alter table public.products   enable row level security;
alter table public.orders     enable row level security;

create policy "categorias: todos leem"       on public.categories for select using (true);
create policy "categorias: equipe gerencia"  on public.categories for all to authenticated using (public.is_staff()) with check (public.is_staff());

create policy "produtos: público vê ativos"  on public.products for select using (active or public.is_staff());
create policy "produtos: equipe gerencia"    on public.products for all to authenticated using (public.is_staff()) with check (public.is_staff());

create policy "pedidos: cliente cria"        on public.orders for insert to anon, authenticated with check (status = 'novo');
create policy "pedidos: equipe gerencia"     on public.orders for all to authenticated using (public.is_staff()) with check (public.is_staff());

-- Fotos (Storage) -----------------------------------------------------------
insert into storage.buckets (id, name, public) values ('products', 'products', true) on conflict (id) do nothing;
create policy "fotos: todos veem"        on storage.objects for select using (bucket_id = 'products');
create policy "fotos: equipe envia"      on storage.objects for insert to authenticated with check (bucket_id = 'products' and public.is_staff());
create policy "fotos: equipe altera"     on storage.objects for update to authenticated using (bucket_id = 'products' and public.is_staff());
create policy "fotos: equipe apaga"      on storage.objects for delete to authenticated using (bucket_id = 'products' and public.is_staff());

-- Atualização em tempo real (a vitrine muda sozinha quando a equipe edita) ----
do $$ begin
  begin alter publication supabase_realtime add table public.products;   exception when duplicate_object then null; end;
  begin alter publication supabase_realtime add table public.categories; exception when duplicate_object then null; end;
  begin alter publication supabase_realtime add table public.orders;     exception when duplicate_object then null; end;
end $$;

